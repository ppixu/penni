import type { PgAjuri } from './ajuri.js';
import { type ControlStore, type KayttajaTiedot, type Sessio, julkinen } from './portti.js';
import { TunnistusVirhe } from './virheet.js';

const SKEEMA = `
CREATE TABLE IF NOT EXISTS kayttaja (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  nimi TEXT,
  salasana_hash TEXT NOT NULL,
  luotu TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessio (
  token_hash TEXT PRIMARY KEY,
  kayttaja_id BIGINT NOT NULL REFERENCES kayttaja(id),
  luotu TEXT NOT NULL,
  vanhenee TEXT NOT NULL,
  viimeksi_kaytetty TEXT NOT NULL
);
`;

function riviKayttajaksi(r: Record<string, unknown>): KayttajaTiedot {
  const nimi = r.nimi;
  return {
    id: Number(r.id),
    email: String(r.email),
    salasanaHash: String(r.salasana_hash),
    luotu: String(r.luotu),
    ...(typeof nimi === 'string' ? { nimi } : {}),
  };
}

export async function luoPostgresControlStore(ajuri: PgAjuri): Promise<ControlStore> {
  await ajuri.exec(SKEEMA);
  return {
    async luoKayttaja({ email, salasanaHash, nimi, aika }) {
      const e = email.toLowerCase();
      const { rows } = await ajuri.query(
        `INSERT INTO kayttaja (email, nimi, salasana_hash, luotu)
         VALUES ($1, $2, $3, $4)
         ON CONFLICT (email) DO NOTHING
         RETURNING id`,
        [e, nimi ?? null, salasanaHash, aika],
      );
      const rivi = rows[0];
      if (!rivi) throw new TunnistusVirhe('EMAIL_VARATTU');
      return julkinen({
        id: Number(rivi.id),
        email: e,
        salasanaHash,
        luotu: aika,
        ...(nimi !== undefined ? { nimi } : {}),
      });
    },
    async haeKayttajaTiedot(id) {
      const { rows } = await ajuri.query('SELECT * FROM kayttaja WHERE id = $1', [id]);
      const r = rows[0];
      return r ? riviKayttajaksi(r) : null;
    },
    async haeKayttajaEmaililla(email) {
      const { rows } = await ajuri.query('SELECT * FROM kayttaja WHERE email = $1', [
        email.toLowerCase(),
      ]);
      const r = rows[0];
      return r ? riviKayttajaksi(r) : null;
    },
    async paivitaSalasana(id, salasanaHash) {
      await ajuri.query('UPDATE kayttaja SET salasana_hash = $1 WHERE id = $2', [salasanaHash, id]);
    },
    async luoSessio(s: Sessio) {
      await ajuri.query(
        `INSERT INTO sessio (token_hash, kayttaja_id, luotu, vanhenee, viimeksi_kaytetty)
         VALUES ($1, $2, $3, $4, $5)`,
        [s.tokenHash, s.kayttajaId, s.luotu, s.vanhenee, s.viimeksiKaytetty],
      );
    },
    async haeSessio(tokenHash) {
      const { rows } = await ajuri.query('SELECT * FROM sessio WHERE token_hash = $1', [tokenHash]);
      const r = rows[0];
      if (!r) return null;
      return {
        tokenHash: String(r.token_hash),
        kayttajaId: Number(r.kayttaja_id),
        luotu: String(r.luotu),
        vanhenee: String(r.vanhenee),
        viimeksiKaytetty: String(r.viimeksi_kaytetty),
      };
    },
    async poistaSessio(tokenHash) {
      await ajuri.query('DELETE FROM sessio WHERE token_hash = $1', [tokenHash]);
    },
  };
}
